function normalizeScenarioName(scenarioName: string | null | undefined): string {
    if (!scenarioName) return '';

    return scenarioName
        .trim()
        .toLowerCase()
        .replace(/^sim-/, '');
}

function parseCellIdSuffixes(raw: string): Set<string> {
    const suffixes = raw
        .split('\n')
        .map((line) => line.trim())
        .filter((line) => line.length > 0)
        .filter((line) => /^\d+\/\d+$/.test(line));

    return new Set(suffixes);
}

export function getOptimalRouteOverlay(scenarioName: string | null | undefined): OptimalRouteOverlay | null {
    const key = normalizeScenarioName(scenarioName);
    if (!key) return null;

    const spec = ROUTES_BY_SCENARIO[key];
    if (!spec) return null;

    return {
        color: spec.color ?? DEFAULT_COLOR,
        cellIdSuffixes: parseCellIdSuffixes(spec.raw)
    };
}
